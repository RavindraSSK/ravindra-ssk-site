/**
 * Precompute real country outlines for the analytics map.
 *
 * Reads Natural Earth 110m country polygons (world-atlas), projects them with
 * a plain web-mercator (so runtime lat/lon -> map math stays a two-line
 * function), and emits lib/world-paths.ts: one SVG path, centroid, and
 * bounding box per country, keyed by ISO 3166-1 alpha-2.
 *
 * Run: node scripts/generate-world-paths.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";
import { geoMercator, geoPath } from "d3-geo";
import { iso31661 } from "iso-3166";

const WIDTH = 1000;
const LAT_MAX = 76; // clip polar emptiness; Antarctica dropped below
const LAT_MIN = -56;

const topo = JSON.parse(
  readFileSync(new URL("../node_modules/world-atlas/countries-110m.json", import.meta.url), "utf8"),
);
const countries = feature(topo, topo.objects.countries).features;

const numericToAlpha2 = new Map(iso31661.map((e) => [e.numeric, e.alpha2]));

// Plain mercator: x from lon linearly, y from mercator(lat); scaled to WIDTH.
const R = WIDTH / (2 * Math.PI);
const mercY = (lat) => R * Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360));
const Y_TOP = mercY(LAT_MAX);
const HEIGHT = Math.round(Y_TOP - mercY(LAT_MIN));

const projection = geoMercator()
  .scale(R)
  .translate([WIDTH / 2, Y_TOP])
  .center([0, 0]);
const path = geoPath(projection);

const out = [];
for (const f of countries) {
  const alpha2 = numericToAlpha2.get(String(f.id).padStart(3, "0"));
  if (!alpha2 || alpha2 === "AQ") continue;
  const d = path(f);
  if (!d) continue;
  const [[x1, y1], [x2, y2]] = path.bounds(f);
  const [cx, cy] = path.centroid(f);
  out.push({
    code: alpha2,
    name: f.properties.name,
    d: d.replace(/(\d+\.\d{2})\d+/g, "$1"),
    bbox: [x1, y1, x2, y2].map((v) => Number(v.toFixed(1))),
    centroid: [Number(cx.toFixed(1)), Number(cy.toFixed(1))],
  });
}

const ts = `/**
 * GENERATED by scripts/generate-world-paths.mjs — do not hand-edit.
 * Natural Earth 110m country outlines, plain web-mercator, ${WIDTH}x${HEIGHT}.
 */

export const MAP_W = ${WIDTH};
export const MAP_H = ${HEIGHT};

/** lat/lon -> map coordinates (same mercator the paths were generated with). */
export function projectLatLon(lat: number, lon: number): [number, number] {
  const x = (lon + 180) * (${WIDTH} / 360);
  const y = ${Y_TOP.toFixed(4)} - ${R.toFixed(4)} * Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360));
  return [x, y];
}

export type CountryShape = {
  code: string;
  name: string;
  d: string;
  bbox: readonly [number, number, number, number];
  centroid: readonly [number, number];
};

export const WORLD_COUNTRIES: readonly CountryShape[] = ${JSON.stringify(out)};

export const COUNTRY_BY_CODE: ReadonlyMap<string, CountryShape> = new Map(
  WORLD_COUNTRIES.map((c) => [c.code, c]),
);
`;
writeFileSync(new URL("../lib/world-paths.ts", import.meta.url), ts);
console.log(`wrote lib/world-paths.ts: ${out.length} countries, ${WIDTH}x${HEIGHT}`);
// sanity: St. Louis
const stl = [(-90.2 + 180) * (WIDTH / 360), Y_TOP - mercY(38.63)];
console.log("St. Louis:", stl.map((v) => v.toFixed(1)).join(","));
